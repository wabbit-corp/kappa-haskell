{-# LANGUAGE OverloadedStrings #-}

module Main (main) where

import qualified Data.ByteString.Char8 as BS8
import Control.Exception (evaluate)
import Data.Text (Text)
import qualified Data.Text as T
import qualified Data.Text.IO as TIO
import Data.Time.Clock (diffUTCTime, getCurrentTime)
import Kappa.Check.Artifact (restoreCheckedPrelude, snapshotCheckedPrelude)
import Kappa.Diagnostic
  ( Diagnostic (dCode, dMessage, dSeverity)
  , Severity (SevError)
  , renderDiagnostic
  )
import Kappa.Pipeline (preludeSourceFingerprint, sourcePreludeArtifactStages)
import Kappa.SemanticHash (sha256BytesHex)
import Kappa.StructuralBinary (encodeStructuralBinary)
import System.Environment (getArgs)
import System.Directory (renameFile)
import System.Exit (die)
import System.IO (hPutStrLn, stderr)

main :: IO ()
main = do
  destination <- getArgs >>= \case
    [path] -> pure path
    _ -> die "usage: gen-kappa-prelude <GeneratedPrelude.hs>"
  let (state, stages) = sourcePreludeArtifactStages
  hPutStrLn stderr "gen-kappa-prelude: checking embedded source"
  checkStages destination state stages
  where
    checkStages destination state [] = do
      let artifact = snapshotCheckedPrelude preludeSourceFingerprint state
      case restoreCheckedPrelude preludeSourceFingerprint artifact of
        Left message ->
          die
            ( "cannot generate an unrestorable checked prelude artifact: "
                <> T.unpack message
            )
        Right _ -> pure ()
      let payload = encodeStructuralBinary artifact
          rendered = renderModule preludeSourceFingerprint (sha256BytesHex payload) payload
          temporary = destination <> ".tmp"
      hPutStrLn stderr "gen-kappa-prelude: encoding checked artifact"
      _ <- evaluate (BS8.length payload)
      hPutStrLn stderr "gen-kappa-prelude: rendering generated module"
      _ <- evaluate (T.length rendered)
      TIO.writeFile temporary rendered
      renameFile temporary destination
    checkStages destination state ((stage, stageDiagnostics) : rest) = do
      started <- getCurrentTime
      diagnosticCount <- evaluate (length stageDiagnostics)
      finished <- getCurrentTime
      hPutStrLn stderr
        ( "gen-kappa-prelude: checked " <> T.unpack stage
            <> " (" <> show diagnosticCount <> " diagnostics)"
            <> " in " <> show (diffUTCTime finished started)
        )
      case filter ((== SevError) . dSeverity) stageDiagnostics of
        [] -> checkStages destination state rest
        firstError : errors -> do
          hPutStrLn stderr
            ( "gen-kappa-prelude: first error "
                <> T.unpack (dCode firstError)
                <> ": "
                <> T.unpack (dMessage firstError)
            )
          die
            ( "cannot generate a checked prelude from an invalid source bootstrap"
                <> " at " <> T.unpack stage
                <> " (showing first "
                <> show displayedErrorLimit
                <> "):\n"
                <> unlines
                     (map (T.unpack . renderDiagnostic)
                       (take displayedErrorLimit (firstError : errors)))
            )
displayedErrorLimit :: Int
displayedErrorLimit = 50

renderModule :: Text -> Text -> BS8.ByteString -> Text
renderModule sourceHash payloadHash payload =
  T.unlines
    [ "-- This module is generated by gen-kappa-prelude. Do not edit its payload."
    , "module Kappa.Check.GeneratedPrelude"
    , "  ( checkedPreludeSourceHash"
    , "  , checkedPreludePayloadHash"
    , "  , checkedPreludePayload"
    , "  ) where"
    , ""
    , "import Data.ByteString (ByteString)"
    , "import qualified Data.ByteString.Char8 as BS8"
    , "import Data.Text (Text)"
    , "import qualified Data.Text as T"
    , ""
    , "checkedPreludeSourceHash :: Text"
    , "checkedPreludeSourceHash = T.pack " <> T.pack (show (T.unpack sourceHash))
    , ""
    , "checkedPreludePayloadHash :: Text"
    , "checkedPreludePayloadHash = T.pack " <> T.pack (show (T.unpack payloadHash))
    , ""
    , "checkedPreludePayload :: ByteString"
    , "checkedPreludePayload = BS8.pack " <> T.pack (show (BS8.unpack payload))
    ]
